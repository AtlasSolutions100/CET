"""Earthwork volume regression: the certified recipes, replayed through
takeoff_engine.earthwork.cut_fill and compared EXACTLY to committed numbers.

Why this exists. Measured 2026-09-01: detect_page._ENGINE_FILES lists ten
modules and earthwork.py is not one of them, so a change to the 134 KB module
that computes the cubic yards a bid depends on moved no signature, invalidated
no cache and tripped no gate. tests/test_grading_zone.py pins the engine to
its own grid arithmetic - self-consistency - not to a recipe a human verified
by eye. This test is the other half: the Oncor C-04 row set whose every
elevation was checked against the sheet (out/verify/2026-08-31/oncor-c04-*),
frozen with its chain polylines, run through cut_fill in every configuration
the harness knows, and compared as floats to
tests/baselines/earthwork_oncor_c04.json.

The baseline is a LITERAL FILE, never regenerated by a test run. A deliberate
volume change re-baselines with `--accept <case-id>` in a commit whose message
says why the numbers moved. The baseline also records earthwork_sig() - a hash
of earthwork.py's import closure (takeoff_engine.regress.earthwork_sig) - so a
code change that happens not to move these particular volumes still surfaces
as "re-baseline or explain" instead of passing silently.

THE PRODUCT PATH IS INSIDE THE FENCE TOO. Until 2026-09-01 this file
hand-copied server._earthwork_run's build step and called cut_fill directly,
so the values a bid actually uses - EarthworkBody's defaults (cell_ft,
surface_model), _layer_stack's inches-to-feet, _page_scale's choice between
the engine's reading and a reviewer's typed scale - were outside it: swapping
the defaults to 4 ft / clamped_ct (-29% cut on Oncor) moved nothing. A
manifest entry with "via": "server" now imports server.py from the tree
under test, writes the fixture's chains as p<N>_result.json into a throwaway
TAKEOFF_JOBS_DIR (ledger under TAKEOFF_LEDGER_DIR), and calls the POST
/earthwork route function (server.earthwork_calc -> _earthwork_run) with a
body that carries NO cell_ft and NO surface_model, so whatever server.py
defaults to is what gets pinned. Layer rows in inches and a reviewer scale
sidecar exercise the offset and page-scale arithmetic. The server defaults
themselves are recorded in the baseline and a change there is a FAIL that
names the field.

What the product path still does NOT cover: the HTTP layer (pydantic
validation of the JSON body, auth, the route decorator), what webui/app.js
puts in that body (which rows, which spot points, how the boundary is drawn),
the /earthwork/map and /earthwork/zone routes, the elevation readers
(/earthwork/suggest), scale DETECTION (the 30 ft/in here is the fixture's,
not read from the sheet), the ledger content, and the approve/export path.

Truth cases are listed in tests/baselines/earthwork_manifest.json, one entry
each, so the DEM-derived truth sheets a parallel pipeline is producing can be
added without editing this file. Every entry and every baseline DECLARES its
comparison kind ("compare": "recipe" | "tolerance") and the two must agree:
a recipe baseline must carry earthwork_sig and cut/fill/net on every case, a
tolerance entry must carry tolerance_yd3 or tolerance_pct and its baseline
all three values. Nothing is inferred from what a file LACKS - until
2026-09-01 the kind was read off the absence of tolerance keys, and deleting
the earthwork_sig key, emptying the per-case dicts, or writing a manifest
with zero cases all printed "N cases passed" with zero numbers compared. Now
a missing required field is a FAIL, a manifest with zero enabled entries is a
FAIL, the run prints "N fields compared" and FAILS when N is 0. Client work whose inputs are gitignored under
out/ (Stice) is REPLAYED ONLY WHEN THOSE INPUTS EXIST LOCALLY, and prints a
visible SKIPPED line otherwise - a silent pass when the client data is absent
would make a laptop without the files look greener than the one with them.
Two more things keep that honest. (1) A gitignored baseline is pinned by a
COMMITTED sha256 of the file (manifest baseline_sha256 -> tests/baselines/
earthwork_stice_p0.sha256: the hash, never the contents), checked whenever
the inputs are present and rewritten by --accept, so a local re-accept after
a volume change shows up in git as a changed hash with a commit message, or
fails the gate. (2) EARTHWORK_REQUIRE=1 in the environment, or --require,
turns SKIPPED into a FAIL with exit 1: set on the machines that hold the
client inputs (this one, the production regress), so "green by absence" is
impossible there; a fresh clone without --require still prints SKIPPED and
is counted, never silently passed.

Dependency-free plain asserts like tests/test_gate.py (needs the repo venv
for numpy/scipy, same as the engine):

    python tests/test_earthwork_regress.py                    # the gate
    python tests/test_earthwork_regress.py --accept oncor_c04 # rewrite ONE baseline
    python tests/test_earthwork_regress.py --tree PATH        # another checkout's
                                                              # takeoff_engine AND
                                                              # server.py against
                                                              # THIS tree's baselines
    python tests/test_earthwork_regress.py --server-tree PATH # server.py from a
                                                              # different tree again
    python tests/test_earthwork_regress.py --require          # a SKIPPED truth
                                                              # case is a FAIL
                                                              # (= EARTHWORK_REQUIRE=1)
    python tests/test_earthwork_regress.py --manifest PATH    # replay a scratch
                                                              # manifest (attacks on the
                                                              # gate itself); the
                                                              # gate uses the
                                                              # committed one

Environment: EARTHWORK_DATA_ROOT resolves the manifest's gitignored input
paths (out/...) against another checkout; default is this repo root.
"""

import argparse
import json
import os
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
BASELINES = HERE / "baselines"
MANIFEST = BASELINES / "earthwork_manifest.json"

GATED = ("cut_yd3", "fill_yd3", "net_yd3")      # compared exactly, as floats
NOTED = ("area_sf", "surface_model", "cell_ft")  # printed when they differ
# the product path also reports what it resolved the offsets and scale to
NOTED_SERVER = ("existing_offset_ft", "proposed_offset_ft", "ft_per_paper_inch")
# EarthworkBody defaults pinned by a "via": "server" baseline - the values a
# bid uses when the operator types nothing. Scalars only; the list fields
# default to empty and the fixture supplies them.
SERVER_DEFAULT_FIELDS = ("cell_ft", "surface_model", "strip_area_sf",
                        "cut_reuse_pct", "export_factor", "import_factor",
                        "boundary")


COMPARE_KINDS = ("recipe", "tolerance")


def _is_num(v) -> bool:
    """A real number. bool is an int in Python and None is not a number:
    `0.0` IS a value here (a sheet with no cut has cut 0.0) and must count."""
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _tolerance(entry) -> float:
    """The band a "tolerance" entry allows, in yd3 for a given baseline value;
    0.0 for a "recipe" entry (exact floats, always)."""
    if entry["compare"] != "tolerance":
        return 0.0
    tol = float(entry.get("tolerance_yd3") or 0.0)
    return tol


def _within(want, got, entry) -> bool:
    """Exact float equality for a "recipe" entry. A "tolerance" entry is a
    TRUTH case - a number that came from outside the engine (a DEM
    differencing, a client's own takeoff) - and passes within the wider of
    tolerance_yd3 and tolerance_pct of the baseline value."""
    if not (_is_num(want) and _is_num(got)):
        return False
    tol = _tolerance(entry)
    if entry["compare"] == "tolerance" and entry.get("tolerance_pct"):
        tol = max(tol, abs(float(want)) * float(entry["tolerance_pct"]) / 100.0)
    return want == got if tol == 0.0 else abs(float(got) - float(want)) <= tol


def _manifest_problems(entry) -> list:
    """Why this manifest entry cannot be trusted to gate anything."""
    bad = []
    kind = entry.get("compare")
    if kind not in COMPARE_KINDS:
        bad.append(f"compare is {kind!r}; must be one of {COMPARE_KINDS}")
        return bad
    if not isinstance(entry.get("runs"), list) or not entry["runs"]:
        bad.append("runs is empty - nothing would be computed")
    if kind == "tolerance":
        if not (float(entry.get("tolerance_yd3") or 0.0) > 0.0
                or float(entry.get("tolerance_pct") or 0.0) > 0.0):
            bad.append("a tolerance entry needs tolerance_yd3 or tolerance_pct > 0")
    else:
        for k in ("tolerance_yd3", "tolerance_pct"):
            if k in entry:
                bad.append(f"a recipe entry must not carry {k} (it would "
                           f"loosen an exact comparison)")
    return bad


def _baseline_problems(base, entry) -> list:
    """Why this baseline file cannot be trusted: every required field, by
    name. A recipe baseline needs earthwork_sig and cut/fill/net on every
    case; a tolerance baseline needs the three values. An empty cases dict,
    an empty case, a null where a number belongs - each is a line here."""
    bad = []
    kind = entry["compare"]
    if base.get("compare") != kind:
        bad.append(f"baseline declares compare {base.get('compare')!r}, "
                   f"manifest says {kind!r}")
    if kind == "recipe":
        sig = base.get("earthwork_sig")
        if not (isinstance(sig, str) and len(sig) == 16):
            bad.append(f"recipe baseline has no earthwork_sig (got {sig!r}) - "
                       f"a code change could not be seen")
    cases = base.get("cases")
    if not isinstance(cases, dict) or not cases:
        bad.append("baseline has no cases - nothing to compare")
        return bad
    for name, c in cases.items():
        if not isinstance(c, dict) or not c:
            bad.append(f"case {name!r} is empty - no volume to compare")
            continue
        for k in GATED:
            if not _is_num(c.get(k)):
                bad.append(f"case {name!r} has no {k} (got {c.get(k)!r})")
    return bad


def _resolve(rel: str, data_root: Path) -> Path:
    p = Path(rel)
    if p.is_absolute():
        return p
    # committed fixtures live in the repo; gitignored recipe inputs (out/...)
    # may live in another checkout's out/, pointed at by EARTHWORK_DATA_ROOT
    q = REPO / p
    if q.exists() or data_root == REPO:
        return q
    return data_root / p


# ---- input loaders: every format becomes the same canonical dict --------
#   {"ft_per_pt", "existing_rows": [{chain_id, z}], "proposed_rows": [...],
#    "chains": {chain_id: [[x, y], ...]}, "boundary": [[x, y], ...] | None,
#    "spots": [{x, y, z}, ...]}

def _load_fixture(entry, data_root):
    """kind 'fixture': one self-contained JSON (tests/baselines/*_inputs.json)."""
    p = _resolve(entry["inputs"], data_root)
    if not p.is_file():
        return None, f"missing {p}"
    fx = json.loads(p.read_text(encoding="utf-8"))
    return {
        "ft_per_pt": float(fx["ft_per_paper_inch"]) / 72.0,
        "existing_rows": fx["existing_rows"],
        "proposed_rows": fx["proposed_rows"],
        "chains": {int(k): v for k, v in fx["chains"].items()},
        "boundary": fx.get("boundary"),
        "spots": fx.get("spots") or [],
    }, str(p)


def _load_seed_flips(entry, data_root):
    """kind 'seed_flips': the offline-recipe layout under out/verify/...:
    seed.json (rows + scale), a detect result (chain polylines), a flips file
    (operator reassignments / drops) and a boundary polygon file."""
    d = _resolve(entry["dir"], data_root)
    paths = {k: d / v for k, v in entry["files"].items()}
    missing = [str(p) for p in paths.values() if not p.is_file()]
    if missing:
        return None, "missing " + ", ".join(missing)
    seed = json.loads(paths["seed"].read_text(encoding="utf-8"))
    res = json.loads(paths["result"].read_text(encoding="utf-8"))
    flips = json.loads(paths["flips"].read_text(encoding="utf-8"))
    b = json.loads(paths["boundary"].read_text(encoding="utf-8"))
    bnd = b["points"] if isinstance(b, dict) else b
    fmap = {int(f["chain_id"]): f["to"] for f in flips}
    ex, pr = [], []
    for r in seed["rows"]:
        to = fmap.get(int(r["chain_id"]))
        if to == "drop":
            continue
        surf = to if to in ("existing", "proposed") else r["surface"]
        row = {"chain_id": int(r["chain_id"]), "z": float(r["z"])}
        if surf == "existing":
            ex.append(row)
        elif surf == "proposed":
            pr.append(row)
    return {
        "ft_per_pt": float(seed["scale"]["ft_per_paper_inch"]) / 72.0,
        "existing_rows": ex,
        "proposed_rows": pr,
        "chains": {int(c["chain_id"]): c["points"] for c in res["chains"]},
        "boundary": bnd,
        "spots": [],
    }, str(d)


LOADERS = {"fixture": _load_fixture, "seed_flips": _load_seed_flips}


def _build(name, rows, chains, np, Surface, points=()):
    """Exactly server._earthwork_run's build(): chain_id -> stored polyline."""
    surf = Surface(name)
    for r in rows:
        cid = int(r["chain_id"])
        if cid in chains:
            surf.contours.append((np.asarray(chains[cid], float), float(r["z"])))
    for q in points:
        surf.points.append((float(q["x"]), float(q["y"]), float(q["z"])))
    return surf


def _boundary_for(case, inputs, np):
    b = case.get("boundary")
    if b is None:
        return None
    if b == "recipe":
        return inputs["boundary"]
    if b == "shrunk75":
        # the recipe hull shrunk 25% about its centroid so the clip actually
        # drops cells and the inside mask is exercised
        P = np.asarray(inputs["boundary"], float)
        c = P.mean(axis=0)
        return (c + 0.75 * (P - c)).round(2).tolist()
    raise ValueError(f"unknown boundary spec {b!r}")


def run_case(case, inputs, np, ew):
    """One cut_fill call; returns the result dict plus _seconds."""
    ex = _build("existing", inputs["existing_rows"], inputs["chains"], np, ew.Surface)
    spots = inputs["spots"][: int(case.get("spots", 0))] if case.get("spots") else ()
    pr = _build("proposed", inputs["proposed_rows"], inputs["chains"], np,
                ew.Surface, points=spots)
    kw = {
        "cell_ft": float(case.get("cell_ft", 2.0)),
        "boundary": _boundary_for(case, inputs, np),
        "surface_model": case.get("surface_model", "auto"),
    }
    for k in ("existing_offset_ft", "proposed_offset_ft"):
        if k in case:
            kw[k] = float(case[k])
    t0 = time.time()
    r = ew.cut_fill(ex, pr, inputs["ft_per_pt"], **kw)
    r = {k: (v.item() if hasattr(v, "item") else v) for k, v in r.items()
         if k != "grid"}
    r["_seconds"] = round(time.time() - t0, 1)
    r["_contours"] = [len(ex.contours), len(pr.contours)]
    return r


def _noted(entry):
    return NOTED + (NOTED_SERVER if entry.get("via") == "server" else ())


def server_defaults(server) -> dict:
    """The scalar defaults of server.EarthworkBody, as the route sees them."""
    d = server.EarthworkBody().model_dump()
    return {k: d.get(k) for k in SERVER_DEFAULT_FIELDS}


def run_case_server(case, inputs, server, job_id, page):
    """The PRODUCT path: server.earthwork_calc (the POST /earthwork route
    function) over a job dir holding the fixture's chains, with a body that
    sets NOTHING the operator would not have typed - no cell_ft, no
    surface_model - so server.py's own defaults, _layer_stack and _page_scale
    are what produce the number."""
    jd = server._job_dir(job_id)
    # The route fails CLOSED on a job dir with no registry row (orphan gate,
    # feat/orphan-fail-closed: `JOBS.get(job_id) or _404()`), exactly as it
    # would for a stray directory on the box - so the fixture job is
    # registered the way an upload would be, as a shared (owner None) row.
    with server.JOBS_LOCK:
        server.JOBS.setdefault(job_id, {
            "path": str(jd / "oncor_c04_fixture.pdf"),
            "name": "oncor_c04_fixture.pdf", "owner": None,
            "pages": page + 1, "sizes": None})
    ft_in = inputs["ft_per_pt"] * 72.0
    res = {"chains": [{"chain_id": cid, "points": pts}
                      for cid, pts in inputs["chains"].items()],
           "scale": {"ft_per_paper_inch": ft_in, "text": f"1\" = {ft_in:g}'",
                     "source": "fixture"}}
    (jd / f"p{page}_result.json").write_text(json.dumps(res), encoding="utf-8")
    # a reviewer-typed scale is a sidecar beside the result (_page_scale reads
    # it; the engine's own reading above stays what it was)
    pick = jd / f"p{page}_scale.json"
    if case.get("scale_ft_per_in") is not None:
        v = float(case["scale_ft_per_in"])
        pick.write_text(json.dumps({"ft_per_paper_inch": v, "text": f"1\" = {v:g}'",
                                    "set_by": "reviewer",
                                    "set_at": "2026-09-01T00:00:00"}),
                        encoding="utf-8")
    else:
        pick.unlink(missing_ok=True)
    import numpy as np
    kw = {"existing": inputs["existing_rows"], "proposed": inputs["proposed_rows"],
          "boundary": _boundary_for(case, inputs, np)}
    if case.get("spots"):
        kw["proposed_points"] = inputs["spots"][: int(case["spots"])]
    for k in ("existing_layers", "proposed_layers"):
        if k in case:
            kw[k] = case[k]
    body = server.EarthworkBody(**kw)
    t0 = time.time()
    resp = server.earthwork_calc(job_id, page, body)
    r = json.loads(bytes(resp.body))
    r = {k: v for k, v in r.items() if k not in ("grid", "layers", "balance")}
    r["_seconds"] = round(time.time() - t0, 1)
    r["_contours"] = [r.get("existing_contours"), r.get("proposed_contours")]
    return r


def _sha256(path: Path) -> str:
    import hashlib
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read_sha_file(path: Path) -> "str | None":
    """First 64-hex token of a sha256sum-style file, or None."""
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            tok = line.strip().split()
            if tok and len(tok[0]) == 64 and all(c in "0123456789abcdef" for c in tok[0]):
                return tok[0]
    except OSError:
        return None
    return None


def _fmt(v):
    return "None" if v is None else (f"{v}" if isinstance(v, (int, float)) else repr(v))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--accept", metavar="CASE_ID",
                    help="rewrite ONE truth case's baseline from this run; "
                         "commit it with a message that says why the numbers moved")
    ap.add_argument("--tree", metavar="PATH",
                    help="import takeoff_engine AND server.py from this checkout "
                         "instead of the one this file lives in (baselines stay "
                         "THIS tree's)")
    ap.add_argument("--server-tree", metavar="PATH",
                    help="import server.py from this checkout (default: --tree)")
    ap.add_argument("--only", metavar="CASE_ID", help="run one truth case")
    ap.add_argument("--require", action="store_true",
                    help="a SKIPPED truth case (inputs absent) is a FAIL, exit 1 "
                         "- same as EARTHWORK_REQUIRE=1 in the environment")
    ap.add_argument("--manifest", metavar="PATH",
                    help="read this manifest instead of the committed one "
                         "(for replaying attacks on the gate; never in CI)")
    args = ap.parse_args(argv)

    tree = Path(args.tree).resolve() if args.tree else REPO
    require = bool(args.require) or (
        os.environ.get("EARTHWORK_REQUIRE", "").strip().lower()
        in ("1", "true", "yes"))
    sys.path.insert(0, str(tree))
    import numpy as np  # noqa: E402
    from takeoff_engine import earthwork as ew  # noqa: E402
    from takeoff_engine import regress  # noqa: E402
    pkg = Path(ew.__file__).resolve().parent
    if pkg.parent != tree:
        print(f"FAIL: takeoff_engine imported from {pkg}, not {tree}")
        return 1
    sig = regress.earthwork_sig(pkg)
    sig_files = regress.earthwork_sig_files(pkg)
    print(f"earthwork_sig {sig}  closure {sig_files}  tree {tree}")
    # what else runs on import and is NOT in the hash because it is not in
    # the tree - printed, never hidden (regress.earthwork_import_hooks)
    hooks = regress.earthwork_import_hooks()
    print("import hooks outside the tree (not hashed): "
          + ("; ".join(hooks) if hooks else "none"))

    data_root = Path(os.environ.get("EARTHWORK_DATA_ROOT") or REPO).resolve()
    manifest_path = Path(args.manifest).resolve() if args.manifest else MANIFEST
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    n_pass = n_fail = 0
    n_fields = 0          # GATED numbers actually compared; 0 is a FAIL
    skipped, failures = [], []

    # the manifest itself: zero enabled entries is a hollow gate, not a pass
    entries = manifest.get("cases")
    if not isinstance(entries, list):
        entries = []
    disabled = [e.get("id") for e in entries if e.get("enabled") is False]
    enabled = [e for e in entries if e.get("enabled") is not False]
    wanted = [e for e in enabled
              if not (args.only and e.get("id") != args.only)
              and not (args.accept and e.get("id") != args.accept)]
    print(f"manifest {manifest_path}: {len(enabled)} enabled entr"
          f"{'y' if len(enabled) == 1 else 'ies'}, {len(wanted)} selected"
          + (f", DISABLED: {', '.join(map(str, disabled))}" if disabled else ""))
    if not enabled:
        failures.append(f"manifest {manifest_path.name} has zero enabled entries "
                        f"- nothing would be compared")
    elif not wanted:
        failures.append(f"no manifest entry matches "
                        f"{args.only or args.accept!r}")
    manifest["cases"] = wanted

    # the product path: server.py from the tree under test, over a throwaway
    # job store so nothing this run writes (results, scale sidecars, ledger
    # events) lands anywhere a demo or a bid reads from
    server = None
    jobs_tmp = None
    if any(e.get("via") == "server" for e in manifest["cases"]):
        import shutil
        import tempfile
        server_tree = (Path(args.server_tree).resolve() if args.server_tree
                       else tree)
        jobs_tmp = Path(tempfile.mkdtemp(prefix="earthwork_gate_jobs_"))
        os.environ["TAKEOFF_JOBS_DIR"] = str(jobs_tmp)
        os.environ["TAKEOFF_LEDGER_DIR"] = str(jobs_tmp / "ledger")
        if str(server_tree) != str(tree):
            sys.path.insert(0, str(server_tree))
        try:
            import server  # noqa: E402
        except RuntimeError as e:
            # server.py mounts webui/ at import; a scratch copy of server.py
            # needs that directory beside it (an empty one is enough)
            print(f"FAIL: import server from {server_tree}: {e}")
            return 1
        sp = Path(server.__file__).resolve()
        if sp.parent != server_tree or sp.name != "server.py":
            print(f"FAIL: server imported from {sp}, not {server_tree}/server.py")
            return 1
        if Path(server.JOBS_DIR).resolve() != jobs_tmp.resolve():
            print(f"FAIL: server.JOBS_DIR is {server.JOBS_DIR}, not the throwaway "
                  f"store {jobs_tmp}")
            return 1
        print(f"server {sp}  jobs/ledger {jobs_tmp}  "
              f"EarthworkBody defaults {server_defaults(server)}")

    for entry in manifest["cases"]:
        cid = entry["id"]
        probs = _manifest_problems(entry)
        if probs:
            for line in probs:
                failures.append(f"{cid}: manifest entry: {line}")
            print(f"\n{cid}: FAIL manifest entry - " + "; ".join(probs))
            continue
        inputs, where = LOADERS[entry["kind"]](entry, data_root)
        if inputs is None:
            print(f"SKIPPED {cid}: inputs not present locally ({where}) - "
                  f"{entry.get('skip_note', 'no volumes were checked for this case')}")
            skipped.append(cid)
            if require:
                failures.append(f"{cid}: SKIPPED, and --require / EARTHWORK_REQUIRE "
                                f"is set: this machine is expected to hold the "
                                f"inputs, so an absent case is a FAIL, not a pass")
            continue
        via_server = entry.get("via") == "server"
        print(f"\n{cid}: {entry['sheet']}\n   inputs {where}"
              + (f"\n   via server.earthwork_calc, page {entry.get('page')}"
                 if via_server else ""))
        results = {}
        for case in entry["runs"]:
            if via_server:
                r = run_case_server(case, inputs, server, f"ewgate-{cid}",
                                    int(entry["page"]))
            else:
                r = run_case(case, inputs, np, ew)
            results[case["name"]] = r
            print(f"   {case['name']:26s} cut {_fmt(r.get('cut_yd3')):>10} "
                  f"fill {_fmt(r.get('fill_yd3')):>10} net {_fmt(r.get('net_yd3')):>10} "
                  f"area {_fmt(r.get('area_sf')):>11} {r.get('surface_model')} "
                  f"{r['_seconds']}s" + (f"  ERROR {r['error']}" if "error" in r else ""))
            # cut_fill widens the cell (x1.5 per step) when the grid would
            # exceed 4M cells and reports the cell it USED. Say so, every
            # run: a capped grid that reads as the requested one is the
            # silent-cap trap (CLAUDE.md s5)
            asked = float(case.get("cell_ft", 2.0)) if not via_server \
                else float(server_defaults(server)["cell_ft"])
            if _is_num(r.get("cell_ft")) and abs(float(r["cell_ft"]) - asked) > 1e-9:
                print(f"      NOTE cell_ft requested {asked:g}, cut_fill used "
                      f"{r['cell_ft']:g} (grid cap widened the cell; the volume "
                      f"above is at {r['cell_ft']:g} ft)")

        bpath = _resolve(entry["baseline"], data_root)
        if args.accept:
            if entry["compare"] != "recipe":
                print(f"   REFUSED --accept {cid}: a tolerance baseline's numbers "
                      f"come from outside the engine and are written by hand")
                return 1
            out = {
                "_about": (f"EXACT cut_fill outputs for manifest case '{cid}'. "
                           f"Written by tests/test_earthwork_regress.py --accept {cid}; "
                           f"a test run never writes here. Change it only in a commit "
                           f"that says which code change moved which number and why."),
                "compare": "recipe",
                "earthwork_sig": sig,
                "earthwork_sig_files": sig_files,
                "accepted": {"tree": str(tree), "date": time.strftime("%Y-%m-%d"),
                             "contours": results[next(iter(results))]["_contours"]},
                "cases": {name: {k: r.get(k) for k in GATED + _noted(entry)}
                          for name, r in results.items()},
            }
            if via_server:
                out["server_defaults"] = server_defaults(server)
            bpath.parent.mkdir(parents=True, exist_ok=True)
            bpath.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8",
                             newline="\n")
            try:
                in_repo = bpath.resolve().relative_to(REPO).parts[0] != "out"
            except ValueError:
                in_repo = False
            print(f"   BASELINE WRITTEN {bpath} (earthwork_sig {sig}) - "
                  + ("commit it with the reason" if in_repo else
                     "gitignored: stays beside the client inputs, never committed"))
            if entry.get("baseline_sha256"):
                shp = REPO / entry["baseline_sha256"]
                digest = _sha256(bpath)
                shp.write_text(f"{digest}  {bpath.name}\n", encoding="utf-8",
                               newline="\n")
                print(f"   SHA256 WRITTEN {shp} = {digest} - commit it: this is "
                      f"how a re-accept of a gitignored baseline shows in git")
            continue

        if not bpath.is_file():
            failures.append(f"{cid}: no baseline at {bpath} - run --accept {cid} "
                            f"and commit it")
            print("   FAIL no baseline")
            n_fail += 1
            continue
        try:
            base = json.loads(bpath.read_text(encoding="utf-8"))
        except ValueError as e:
            failures.append(f"{cid}: baseline {bpath.name} is not JSON: {e}")
            print("   FAIL baseline unreadable")
            n_fail += 1
            continue
        if not isinstance(base, dict):
            base = {}
        # -1. a gitignored baseline is pinned by a committed hash of its
        #     bytes. Mismatch = someone re-accepted it locally and did not
        #     commit the new hash with a reason; absent = never pinned.
        if entry.get("baseline_sha256"):
            shp = REPO / entry["baseline_sha256"]
            want_sha, got_sha = _read_sha_file(shp), _sha256(bpath)
            if want_sha is None:
                failures.append(f"{cid}: no committed sha256 for {bpath.name} at "
                                f"{shp} - run --accept {cid} and commit the hash")
            elif want_sha != got_sha:
                failures.append(f"{cid}: {bpath.name} sha256 {got_sha[:16]}... does "
                                f"not match the committed {want_sha[:16]}... in "
                                f"{shp.name} - the gitignored baseline was "
                                f"re-accepted locally; commit the new hash with the "
                                f"reason, or restore the baseline")
            print(f"   sha256 {got_sha[:16]}... "
                  f"{'matches' if want_sha == got_sha else 'MISMATCH vs'} "
                  f"{shp.relative_to(REPO)}")
        # 0. the baseline's shape, field by field. A recipe baseline that
        #    lost its earthwork_sig, a case dict emptied out, a null where a
        #    volume belongs: each is a named FAIL, never a quieter pass.
        probs = _baseline_problems(base, entry)
        for line in probs:
            failures.append(f"{cid}: baseline {bpath.name}: {line}")
        # 1. the code fingerprint: a change in the hashed closure with no
        #    volume change must still surface. Required on a recipe baseline
        #    (checked above); compared on a tolerance one only if it chose
        #    to record it.
        if "earthwork_sig" in base and base.get("earthwork_sig") != sig:
            failures.append(
                f"{cid}: earthwork_sig moved: baseline {base.get('earthwork_sig')} "
                f"(closure {base.get('earthwork_sig_files')}) now {sig} "
                f"(closure {sig_files}) - the volume code changed; re-baseline "
                f"with --accept {cid} and say why, or explain why the volumes "
                f"must not move")
        # 2. the product's defaults: what the route uses when the body says
        #    nothing. A cell or model swap there moves a bid and, until
        #    2026-09-01, no test; the numbers below would catch cell/model,
        #    this catches the rest (balance factors, strip area, boundary)
        if via_server:
            want_d, got_d = base.get("server_defaults") or {}, server_defaults(server)
            for k in SERVER_DEFAULT_FIELDS:
                if want_d.get(k, "<absent>") != got_d.get(k):
                    failures.append(f"{cid}: server default {k} baseline "
                                    f"{_fmt(want_d.get(k, '<absent>'))} now "
                                    f"{_fmt(got_d.get(k))} - EarthworkBody changed; "
                                    f"re-baseline with --accept {cid} and say why")
        # 3. the volumes, exactly (or within the declared band)
        want_cases = set(base.get("cases") or {})
        got_cases = set(results)
        for name in sorted(want_cases - got_cases):
            failures.append(f"{cid}/{name}: in baseline but not in the manifest runs")
        for name in sorted(got_cases - want_cases):
            failures.append(f"{cid}/{name}: run but has no baseline entry")
        for name in sorted(want_cases & got_cases):
            want, got = base["cases"][name], results[name]
            if not isinstance(want, dict):
                want = {}
            bad, compared = [], 0
            for k in GATED:
                w, g = want.get(k), got.get(k)
                if not _is_num(w):
                    continue        # already a FAIL line from _baseline_problems
                compared += 1
                if not _within(w, g, entry):
                    bad.append((k, w, g))
            n_fields += compared
            for k, w, g in bad:
                delta = round(g - w, 3) if (_is_num(w) and _is_num(g)) else None
                band = _tolerance(entry)
                if entry["compare"] == "tolerance" and entry.get("tolerance_pct"):
                    band = max(band, abs(float(w)) * float(entry["tolerance_pct"]) / 100.0)
                failures.append(f"{cid}/{name}: {k} baseline {_fmt(w)} got {_fmt(g)} "
                                f"(delta {_fmt(delta)}"
                                + (f", band +/-{band:.1f}" if band else "") + ")")
            for k in _noted(entry):
                if k in want and want.get(k) != got.get(k):
                    print(f"   NOTE {name}: {k} baseline {_fmt(want.get(k))} "
                          f"now {_fmt(got.get(k))}")
            if bad or compared < len(GATED):
                n_fail += 1
            else:
                n_pass += 1
        if probs:
            n_fail += max(0, len(want_cases - got_cases))
        print(f"   baseline {bpath.name} compare {base.get('compare')!r} "
              f"sig {base.get('earthwork_sig')} "
              f"{'OK' if base.get('earthwork_sig') == sig else 'MOVED'}"
              + (f"  {len(probs)} shape problem(s)" if probs else ""))

    if jobs_tmp is not None:
        shutil.rmtree(jobs_tmp, ignore_errors=True)
    if args.accept:
        return 0
    print()
    if n_fields == 0:
        failures.append("0 fields compared - no cut/fill/net number was checked "
                        "against a baseline; a gate that compares nothing has "
                        "not passed")
    for f in failures:
        print("FAIL " + f)
    print(f"\nearthwork gate: {n_fields} fields compared; {n_pass} cases passed, "
          f"{n_fail} failed, {len(skipped)} truth case(s) SKIPPED"
          + (f" ({', '.join(skipped)})" if skipped else "")
          + f"; {len(failures)} failure line(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
